// ============================================
// make-freeways.mjs -- the freeways round home, for the Around home map
// ============================================
// Reads Natural Earth's 10m roads (public domain; download
// ne_10m_roads.geojson from github.com/nvkelso/natural-earth-vector and pass
// its path) and writes src/lib/freeways.js. Natural Earth numbers a few of
// them wrongly here, so each is named by where it runs, not by its "name":
// its "210" from Pomona east is I-10, its "10" from Pomona to Beaumont is
// SR-60, and its "215" through Pasadena is I-210. It has no SR-210 (the
// Foothill Freeway through Rancho Cucamonga, Fontana and Rialto), so that one
// is traced by hand through its interchanges, to within a few hundred metres.
//   node scripts/make-freeways.mjs path/to/ne_10m_roads.geojson

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const src = process.argv[2]
if (!src) { console.error('Pass the path to ne_10m_roads.geojson'); process.exit(1) }
const roads = JSON.parse(fs.readFileSync(src, 'utf8'))
const BOX = [-118.05, 33.8, -116.65, 34.5] // a little beyond Around home, so lines run off its edges
const inBox = ([x, y]) => x >= BOX[0] && x <= BOX[2] && y >= BOX[1] && y <= BOX[3]

// Which freeway a Natural Earth line is, from its number and where it runs
function which(name, line) {
  const xs = line.map((c) => c[0]), ys = line.map((c) => c[1])
  const midX = (Math.min(...xs) + Math.max(...xs)) / 2, midY = (Math.min(...ys) + Math.max(...ys)) / 2
  if (name === '210' && midX > -117.85) return 'I-10'
  if (name === '10' && midX < -116.99 && midY < 34.05 && Math.min(...xs) > -118.1) return 'SR-60'
  if (name === '10') return 'I-10'
  if (name === '215' && midX < -117.75) return 'I-210'
  if (name === '215') return 'I-215'
  if (name === '15') return 'I-15'
  if (['91', '71', '57', '30', '83', '259'].includes(name)) return 'SR-' + name
  return null
}

const out = {}
for (const f of roads.features) {
  const p = f.properties
  if (p.sov_a3 !== 'USA' || p.type !== 'Major Highway') continue
  const lines = f.geometry.type === 'LineString' ? [f.geometry.coordinates] : f.geometry.coordinates
  for (const line of lines) {
    if (!line.some(inBox)) continue
    const k = which(p.name, line)
    if (!k) continue
    ;(out[k] ||= []).push(line.map(([x, y]) => [+x.toFixed(3), +y.toFixed(3)]))
  }
}
// SR-210, by hand: I-210 at San Dimas, Upland, Rancho Cucamonga, I-15, Fontana,
// Rialto, I-215, Highland, then south to I-10 at Redlands
out['SR-210'] = [[[-117.807, 34.105], [-117.735, 34.118], [-117.66, 34.122], [-117.575, 34.128], [-117.533, 34.127], [-117.47, 34.135], [-117.435, 34.136], [-117.37, 34.133], [-117.31, 34.146], [-117.245, 34.137], [-117.2, 34.128], [-117.185, 34.098], [-117.178, 34.064]]]

// Where each one's number sits on the Around home map
const LABEL = { 'I-10': [-117.62, 34.07], 'SR-60': [-117.47, 34.006], 'I-15': [-117.55, 34.04], 'I-215': [-117.335, 34.17], 'SR-210': [-117.62, 34.124], 'SR-91': [-117.43, 33.925], 'SR-71': [-117.72, 34.0], 'SR-57': [-117.84, 34.0], 'I-210': [-117.84, 34.12] }
const list = Object.entries(out).map(([id, lines]) => ({ id, num: id.split('-')[1], interstate: id.startsWith('I-'), lines, label: LABEL[id] || null }))
  .sort((a, b) => a.id.localeCompare(b.id))

const file = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'src', 'lib', 'freeways.js')
fs.writeFileSync(file, `// Generated by scripts/make-freeways.mjs from Natural Earth's roads (public domain),
// renumbered where it numbers them wrongly, with SR-210 traced by hand.
// Regenerate rather than edit. [lng, lat] points; \`label\` is where its number sits.

export const FREEWAYS = ${JSON.stringify(list)}
`)
console.log(list.map((f) => `${f.id}: ${f.lines.length} lines`).join('\n'))
